import scipy.ndimage

def resample_bands(src_bands, ref_bands):
    """
    Función auxiliar.
    Realiza el re-muestreo según la resolución elegida.
    Corrección: Se ha modificado la forma de calcular el zoom factor (zf)
    para que sea compatible con todas las bandas, así como la forma de
    asignar la salida al array src_resample, utilizando el slicing adecuado
    para evitar problemas de broadcasting.
    """
    b = src_bands.shape[0]
    r = ref_bands.shape[1]
    c = ref_bands.shape[2]
    zf = (r / src_bands.shape[1], c / src_bands.shape[2]) # Cálculo de zoom factor para cada dimensión
    src_resample = np.zeros((b, r, c), dtype=src_bands.dtype) # Se agrega dtype para que el tipo de dato sea igual que el de src_bands
    for i, band in enumerate(src_bands):
        src_resample[i] = scipy.ndimage.zoom(band, zf, output=src_bands.dtype) # output dtype se agrega para consistencia
    return src_resample

